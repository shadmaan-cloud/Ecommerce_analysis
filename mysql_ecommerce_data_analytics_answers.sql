/* Q1. Customer Revenue Analysis
Find every customer who has placed at least one order.
Show:
- customer_id
- customer name
- number of orders
- total quantity purchased
- total revenue
Sort by total revenue from highest to lowest. */

SELECT C.CUSTOMER_ID,
CONCAT(C.FIRST_NAME, ' ',C.LAST_NAME) AS CUSTOMER_NAME,
COUNT(DISTINCT O.ORDER_ID) AS TOTAL_ORDERS,
SUM(PO.QUANTITY) AS TOTAL_QUANTITY,
SUM(PO.QUANTITY*PO.UNIT_PRICE) AS TOTAL_REVENUE
FROM CUSTOMERS C JOIN ORDERS O ON C.CUSTOMER_ID = O.CUSTOMER_ID 
JOIN PRODUCT_ORDERS PO ON O.ORDER_ID = PO.ORDER_ID
GROUP BY C.CUSTOMER_ID
ORDER BY TOTAL_REVENUE DESC;

