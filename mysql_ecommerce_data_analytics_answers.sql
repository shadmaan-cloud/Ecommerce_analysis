(
    SELECT AVG(OV.VALUE)
    FROM (
        SELECT SUM(PO2.QUANTITY * PO2.UNIT_PRICE) AS VALUE
        FROM ORDERS O2
        JOIN PRODUCT_ORDERS PO2 ON O2.ORDER_ID = PO2.ORDER_ID
        WHERE O2.CUSTOMER_ID = O.CUSTOMER_ID
        GROUP BY O2.ORDER_ID
    ) AS OV
