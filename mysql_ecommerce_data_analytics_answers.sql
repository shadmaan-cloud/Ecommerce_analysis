/* Q23. Orders Above the Customer's Average Order Value
Find orders whose value is greater than the average order
value of the same customer.

Show:
- order_id
- customer_id
- order_date
- order_value
- customer_average_order_value */

SELECT O.ORDER_ID, O.CUSTOMER_ID, O.ORDER_DATE,
