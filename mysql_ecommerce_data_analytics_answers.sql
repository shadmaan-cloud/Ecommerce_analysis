/* Q26. Second-Highest Revenue Product
Find the product with the second-highest total revenue.

Use a subquery rather than LIMIT/OFFSET. */

SELECT PR.PRODUCT_ID, PR.PRODUCT_NAME, PR.PRODUCT_TYPE, PR.TOTAL_REVENUE
FROM (
    SELECT P.PRODUCT_ID, P.PRODUCT_NAME, P.PRODUCT_TYPE,
    SUM(PO.QUANTITY * PO.UNIT_PRICE) AS TOTAL_REVENUE
    FROM PRODUCTS P
    JOIN PRODUCT_ORDERS PO ON P.PRODUCT_ID = PO.PRODUCT_ID
    GROUP BY P.PRODUCT_ID, P.PRODUCT_NAME, P.PRODUCT_TYPE
) AS PR
WHERE PR.TOTAL_REVENUE = (
    SELECT MAX(SUB.TOTAL_REVENUE)
    FROM (
        SELECT SUM(PO2.QUANTITY * PO2.UNIT_PRICE) AS TOTAL_REVENUE
        FROM PRODUCT_ORDERS PO2
        GROUP BY PO2.PRODUCT_ID
    ) AS SUB
    WHERE SUB.TOTAL_REVENUE < (
        SELECT MAX(SUB2.TOTAL_REVENUE)
        FROM (
            SELECT SUM(PO3.QUANTITY * PO3.UNIT_PRICE) AS TOTAL_REVENUE
            FROM PRODUCT_ORDERS PO3
            GROUP BY PO3.PRODUCT_ID
        ) AS SUB2
    )
);
