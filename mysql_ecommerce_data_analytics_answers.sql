/* Q18. Customers With Increasing Order Activity
Find customers whose last order value is greater than their
first order value.

Return:
- customer_id
- first_order_value
- last_order_value
- increase_amount */

WITH ORDER_VALUES AS (
    SELECT O.ORDER_ID, O.CUSTOMER_ID, O.ORDER_DATE,
    SUM(PO.QUANTITY * PO.UNIT_PRICE) AS ORDER_VALUE
    FROM ORDERS O
    JOIN PRODUCT_ORDERS PO ON O.ORDER_ID = PO.ORDER_ID
    GROUP BY O.ORDER_ID, O.CUSTOMER_ID, O.ORDER_DATE
),
FIRST_LAST AS (
    SELECT CUSTOMER_ID,
    FIRST_VALUE(ORDER_VALUE) OVER (PARTITION BY CUSTOMER_ID ORDER BY ORDER_DATE, ORDER_ID) AS FIRST_ORDER_VALUE,
    FIRST_VALUE(ORDER_VALUE) OVER (PARTITION BY CUSTOMER_ID ORDER BY ORDER_DATE DESC, ORDER_ID DESC) AS LAST_ORDER_VALUE
    FROM ORDER_VALUES
)
SELECT DISTINCT CUSTOMER_ID, FIRST_ORDER_VALUE, LAST_ORDER_VALUE,
(LAST_ORDER_VALUE - FIRST_ORDER_VALUE) AS INCREASE_AMOUNT
FROM FIRST_LAST
WHERE LAST_ORDER_VALUE > FIRST_ORDER_VALUE
ORDER BY INCREASE_AMOUNT DESC;

/* Q19. Orders Above Monthly Average
Using CTEs, calculate each order's value and the average
