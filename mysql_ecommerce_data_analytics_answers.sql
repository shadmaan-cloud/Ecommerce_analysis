/* Q14. Monthly Revenue Growth
Calculate monthly revenue and compare each month with the
previous month using LAG().
Show:
- month
- monthly_revenue
- previous_month_revenue
- revenue_change
- growth_percentage */

WITH MONTHLY_REVENUE AS (
    SELECT DATE_FORMAT(O.ORDER_DATE, '%Y-%m') AS MONTH,
    SUM(PO.QUANTITY * PO.UNIT_PRICE) AS MONTHLY_REVENUE
    FROM ORDERS O
    JOIN PRODUCT_ORDERS PO ON O.ORDER_ID = PO.ORDER_ID
    GROUP BY DATE_FORMAT(O.ORDER_DATE, '%Y-%m')
)
SELECT MONTH, MONTHLY_REVENUE,
LAG(MONTHLY_REVENUE) OVER (ORDER BY MONTH) AS PREVIOUS_MONTH_REVENUE,
MONTHLY_REVENUE - LAG(MONTHLY_REVENUE) OVER (ORDER BY MONTH) AS REVENUE_CHANGE,
ROUND(
    (MONTHLY_REVENUE - LAG(MONTHLY_REVENUE) OVER (ORDER BY MONTH))
    / LAG(MONTHLY_REVENUE) OVER (ORDER BY MONTH) * 100, 2
) AS GROWTH_PERCENTAGE
FROM MONTHLY_REVENUE
ORDER BY MONTH;

/* Q15. Customer Purchase Segmentation
Using a CTE, calculate each customer's:
- total orders
- total revenue

Then classify customers as:
- High Value: revenue >= 1000
- Medium Value: revenue >= 500 and < 1000
- Low Value: revenue < 500

Return customer_id, customer_name, orders, revenue, segment. */

WITH CUSTOMER_SUMMARY AS (
    SELECT C.CUSTOMER_ID,
    CONCAT(C.FIRST_NAME, ' ', C.LAST_NAME) AS CUSTOMER_NAME,
    COUNT(DISTINCT O.ORDER_ID) AS TOTAL_ORDERS,
    SUM(PO.QUANTITY * PO.UNIT_PRICE) AS TOTAL_REVENUE
    FROM CUSTOMERS C
    JOIN ORDERS O ON C.CUSTOMER_ID = O.CUSTOMER_ID
    JOIN PRODUCT_ORDERS PO ON O.ORDER_ID = PO.ORDER_ID
    GROUP BY C.CUSTOMER_ID, C.FIRST_NAME, C.LAST_NAME
)
SELECT CUSTOMER_ID, CUSTOMER_NAME, TOTAL_ORDERS, TOTAL_REVENUE,
CASE
    WHEN TOTAL_REVENUE >= 1000 THEN 'High Value'
    WHEN TOTAL_REVENUE >= 500 THEN 'Medium Value'
    ELSE 'Low Value'
END AS SEGMENT
FROM CUSTOMER_SUMMARY
ORDER BY TOTAL_REVENUE DESC;

