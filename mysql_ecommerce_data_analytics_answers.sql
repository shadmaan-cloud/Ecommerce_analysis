/* Q12. Order Contribution to Customer Revenue
For every order, calculate:
- order value
- customer's total revenue
- percentage of customer revenue contributed by that order

Use a window function to calculate the customer total. */

WITH ORDER_VALUES AS (
    SELECT O.ORDER_ID, O.CUSTOMER_ID,
    SUM(PO.QUANTITY * PO.UNIT_PRICE) AS ORDER_VALUE
    FROM ORDERS O
    JOIN PRODUCT_ORDERS PO ON O.ORDER_ID = PO.ORDER_ID
    GROUP BY O.ORDER_ID, O.CUSTOMER_ID
)
SELECT ORDER_ID, CUSTOMER_ID, ORDER_VALUE,
SUM(ORDER_VALUE) OVER (PARTITION BY CUSTOMER_ID) AS CUSTOMER_TOTAL_REVENUE,
