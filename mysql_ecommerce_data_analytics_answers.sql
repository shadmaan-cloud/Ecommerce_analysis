/* Q20. Customer Retention / Repeat Purchase Analysis
Using CTEs, find customers who placed at least 2 orders.
Show:
- customer_id
- first_order_date
- last_order_date
- total_orders
- days_between_first_and_last_order */

WITH CUSTOMER_ORDERS AS (
    SELECT CUSTOMER_ID,
    MIN(ORDER_DATE) AS FIRST_ORDER_DATE,
    MAX(ORDER_DATE) AS LAST_ORDER_DATE,
    COUNT(*) AS TOTAL_ORDERS
    FROM ORDERS
    GROUP BY CUSTOMER_ID
)
SELECT CUSTOMER_ID, FIRST_ORDER_DATE, LAST_ORDER_DATE, TOTAL_ORDERS,
DATEDIFF(LAST_ORDER_DATE, FIRST_ORDER_DATE) AS DAYS_BETWEEN_FIRST_AND_LAST_ORDER
FROM CUSTOMER_ORDERS
WHERE TOTAL_ORDERS >= 2
ORDER BY TOTAL_ORDERS DESC;

/* Q21. Customers Spending Above Average
Find customers whose total revenue is greater than the
average revenue of all customers who have placed orders.

Show:
